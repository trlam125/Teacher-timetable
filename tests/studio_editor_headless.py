"""Outline, presentation and rich-content editing against disposable harness."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

ROOT=Path(__file__).resolve().parents[1]
ARTIFACT=ROOT/'tmp/ai-studio-qa'
checks=[]
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True)
 page=browser.new_page(viewport={'width':1440,'height':1000},accept_downloads=True)
 page.set_default_timeout(10000)
 errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
 page.goto('http://127.0.0.1:8766/ai-studio');page.wait_for_load_state('networkidle')
 page.locator('#new-deck').click()
 page.locator('[name=subject]').fill('Vật lí')
 page.locator('[name=grade]').fill('Lớp 9')
 page.locator('[name=lesson_title]').fill('Định luật Ôm — chỉnh dàn ý')
 page.locator('[name=slide_count]').fill('5');page.locator('#cloud-consent').check()
 page.get_by_role('button',name='Tạo dàn ý bằng AI',exact=True).click()
 expect(page.locator('#deck-status')).to_contain_text('Đã có dàn ý')
 page.locator('#edit-outline').click()
 rows=page.locator('#outline-rows > article')
 expect(rows).to_have_count(5)
 rows.nth(0).locator('[name=outline_title]').fill('Mở đầu đã chỉnh')
 rows.nth(0).get_by_role('button',name='Đưa slide xuống',exact=True).click()
 expect(rows.nth(1).locator('[name=outline_title]')).to_have_value('Mở đầu đã chỉnh')
 rows.nth(0).locator('[name=outline_seconds]').fill('600')
 rows.nth(1).locator('[name=outline_seconds]').fill('480')
 rows.nth(2).locator('[name=outline_kind]').select_option('chart')
 page.screenshot(path=str(ARTIFACT/'outline-editor-desktop.png'),full_page=True)
 page.locator('#outline-form').get_by_role('button',name='Lưu dàn ý',exact=True).click()
 expect(page.locator('#slide-list button').nth(1)).to_contain_text('Mở đầu đã chỉnh')
 page.reload();expect(page.locator('#slide-list button').nth(1)).to_contain_text('Mở đầu đã chỉnh')
 checks.append('manual outline edit/reorder/duration persisted across reload')
 page.locator('#continue-deck').click();expect(page.locator('#export-pptx')).to_be_visible()
 before=page.locator('#slide-preview').inner_text()
 page.locator('.studio-presentation summary').click()
 page.locator('#presentation-theme').select_option('history')
 page.locator('#presentation-motion').select_option('none')
 page.locator('#presentation-form button').click()
 expect(page.locator('#studio-message')).to_contain_text('giao diện')
 page.reload();expect(page.locator('#presentation-theme')).to_have_value('history')
 expect(page.locator('#presentation-motion')).to_have_value('none')
 assert page.locator('#slide-preview').inner_text()==before
 checks.append('theme and motion save without regenerating or removing authored content')
 page.locator('#slide-list button').filter(has_text='phần 3').click()
 expect(page.locator('#chart-editor')).to_be_visible()
 page.locator('#chart-series').fill('Dữ liệu do giáo viên chỉnh')
 page.locator('#chart-type').select_option('line')
 page.locator('#chart-values').fill('3 V | 1\n6 V | 2\n9 V | 3')
 page.locator('#slide-form button').click()
 page.reload();expect(page.locator('#chart-series')).to_have_value('Dữ liệu do giáo viên chỉnh')
 expect(page.locator('#chart-values')).to_have_value('3 V | 1\n6 V | 2\n9 V | 3')
 checks.append('native chart type and numeric series are editable and persist')
 quiz=page.locator('#slide-list button').filter(has_text='phần 4')
 quiz.click();expect(page.locator('#quiz-editor')).to_be_visible()
 page.locator('#quiz-question').fill('U=9 V, R=3 Ω. I bằng bao nhiêu?')
 page.locator('#quiz-options').fill('1 A\n3 A\n6 A')
 page.locator('#quiz-correct').select_option('1')
 page.locator('#quiz-explanation').fill('I=U/R=9/3=3 A.')
 page.locator('#slide-form button').click()
 expect(page.locator('#slide-preview')).to_contain_text('U=9 V')
 page.reload();expect(page.locator('#quiz-question')).to_have_value('U=9 V, R=3 Ω. I bằng bao nhiêu?')
 checks.append('quiz question/options/answer/explanation can be edited manually and reloaded')
 calls=[]
 page.on('request',lambda request:calls.append(request.url) if request.method=='POST' and request.url.rsplit('/',1)[-1] in {'plan','author','propose','inspect-sources'} else None)
 page.locator('#quiz-explanation').fill('9/3=4 A.')
 page.locator('#quiz-options').fill('0.5 A\n1/2 A\n3 A')
 page.locator('#slide-form button').click()
 expect(page.locator('#content-review')).to_contain_text('phép tính')
 expect(page.locator('#content-review')).to_contain_text('tương đương')
 page.reload()
 expect(page.locator('#content-review')).to_contain_text('tương đương')
 page.locator('#quiz-explanation').fill('I=U/R=9/3=3 A.')
 page.locator('#quiz-options').fill('1 A\n3 A\n6 A')
 page.locator('#slide-form button').click()
 expect(page.locator('#content-review')).not_to_contain_text('phép tính')
 expect(page.locator('#content-review')).not_to_contain_text('tương đương')
 assert not calls
 checks.append('manual arithmetic and equivalent-answer warnings persist, clear after correction and make no AI calls')
 page.locator('#quiz-question').fill('Làm bài tập SGK trang 999?')
 page.locator('#slide-form button').click()
 expect(page.locator('#content-review')).to_contain_text('số trang')
 page.locator('#export-pptx').click()
 expect(page.locator('#studio-message')).to_contain_text('rà soát')
 page.locator('#content-review-ack').check()
 with page.expect_download() as pending:page.locator('#export-pptx').click()
 pending.value.save_as(ARTIFACT/'reviewed-editor-export.pptx')
 checks.append('unverified book/page reference is visible and requires acknowledgement before export')
 page.screenshot(path=str(ARTIFACT/'rich-editor-desktop.png'),full_page=True)
 page.locator('#edit-outline').click();page.locator('#outline-discard').check()
 page.locator('#outline-form').get_by_role('button',name='Lưu dàn ý',exact=True).click()
 expect(page.locator('#export-pptx')).not_to_be_visible()
 page.locator('#undo-deck').click();expect(page.locator('#export-pptx')).to_be_visible()
 checks.append('explicit outline restart clears authored content and undo restores it')
 page.locator('#new-deck').click()
 page.locator('#document-file').set_input_files(ARTIFACT/'book-150-pages.pdf')
 expect(page.locator('#document-name')).to_contain_text('150 trang PDF',timeout=20000)
 page.locator('#book-search-query').fill('Lesson page 35')
 page.locator('#search-book').click()
 expect(page.locator('#book-search-results')).to_contain_text('trang PDF 35',timeout=30000)
 page.locator('#book-search-results button').first.click()
 expect(page.locator('#page-first')).to_have_value('35')
 expect(page.locator('#page-last')).to_have_value('35')
 checks.append('on-device PDF content search selects the matching page without uploading the book')
 page.set_viewport_size({'width':390,'height':844})
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
 assert not errors,errors
 checks.append('mobile layout and no uncaught browser errors')
 browser.close()
report={'passed':len(checks),'checks':checks,'provider':'test-only fixture'}
(ARTIFACT/'editor-headless-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(report,ensure_ascii=False))
